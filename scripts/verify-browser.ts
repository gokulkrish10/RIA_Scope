// Deliberately synthetic transport/model; real HTTP, browser, SQLite, worker and UI.
const root = resolve('.data', `browser-verification-${Date.now()}`);
await mkdir(root, { recursive: true, mode: 0o700 });
const token = 'synthetic-browser-backend-token-1234567890';
const password = 'synthetic-browser-password-1234567890';
const reviewer = '225dcc34-f02c-4c79-8bbc-d3d412730c53';
const previous = 'SYNTHETIC TEST ONLY. Central Bank of Kenya circular E2E/2020/1. Banks must complete review by 2026-12-31.';
const current = 'SYNTHETIC TEST ONLY. This amends Central Bank of Kenya circular E2E/2020/1. Banks must complete review by 2027-03-31 instead of 2026-12-31.';
const db = new Database(resolve(root, 'ria.sqlite'));
const repository = new Repository(db);
const source = { ...cbkSource(repository.now()), name: 'SYNTHETIC browser test source' };
repository.seedSource(source, 'synthetic-browser', {});
const storage = new OriginalStorage(resolve(root, 'originals'));
const cite = (v: VersionText) => ({ documentId: v.documentId, versionId: v.versionId, locator: v.segments[0]!.locator, ...(v.segments[0]!.pageNumber ? { pageNumber: v.segments[0]!.pageNumber } : {}), excerpt: v.segments[0]!.text });
const analysis = new AnalysisService(repository, new AnalysisEngine({ identity: 'synthetic-browser-model', async generate(_prompt, payload) {
  const input = payload as VersionText & { current?: VersionText; previous?: VersionText };
  if (input.current) return { evidenceComplete: true, unresolvedReason: null, changes: [{ id: randomUUID(), classification: 'deadlineChanged', before: cite(input.previous!), after: cite(input.current), explanation: 'SYNTHETIC TEST: review deadline extended by three months.', deadlineDirection: 'extended', previousDeadline: '2026-12-31', updatedDeadline: '2027-03-31' }] };
  const amended = input.segments.some(s => s.text.includes('amends'));
  return { documentStatus: null, statusEvidence: [], effectiveDate: null, effectiveDateEvidence: [], businessAreas: ['banking'], obligations: [{ text: 'SYNTHETIC TEST: complete review by the stated deadline.', requirementStatus: 'mandatory', businessAreas: ['banking'], applicableEntities: ['Banks'], departments: [], regulatedActivities: [], effectiveDate: null, complianceDeadline: amended ? '2027-03-31' : '2026-12-31', evidence: [cite(input)] }], references: amended ? [{ referenceText: 'Central Bank of Kenya circular E2E/2020/1', referenceNumber: 'E2E/2020/1', issuingAuthority: 'Central Bank of Kenya', relation: 'amends', evidence: [cite(input)] }] : [] };
} }), 0);
const adapter: SourceAdapter = { key: 'synthetic-browser', allowedHosts: ['www.centralbank.go.ke'], async discover() { return [{ canonicalKey: 'synthetic-current', title: 'SYNTHETIC browser amendment', kind: 'circular', referenceNumber: 'E2E/2026/2', publicationDate: null, effectiveDate: null, downloadUrl: 'https://www.centralbank.go.ke/synthetic.txt', mediaType: 'text/plain' }]; } };
const fetcher: OfficialFetcher = { async get(url) { return { bytes: Buffer.from(current), contentType: 'text/plain', finalUrl: url }; } };
const worker = new Worker(repository, storage, new Map([[adapter.key, adapter]]), () => fetcher, 0, 60_000, id => { analysis.requestAnalysis(id); });
const backend = createHttpServer(repository, token, { analysis, storage, reviewerId: reviewer });
await new Promise<void>(done => backend.listen(0, '127.0.0.1', done));
const address = backend.address(); assert.ok(address && typeof address !== 'string');
const backendUrl = `http://127.0.0.1:${address.port}`;
const gateway = frontendGateway({ RIA_WRITE_TOKEN: token, RIA_FRONTEND_USER: 'test', RIA_FRONTEND_PASSWORD: password, RIA_API_ORIGIN: backendUrl });
const vite = await createServer({ configFile: false, plugins: gateway.plugins, server: { host: '127.0.0.1', port: 4178, strictPort: true, proxy: gateway.proxy, fs: { deny: ['.env', '.env.*', '**/.data/**', '**/*.sqlite*', '**/.git/**'] } } });
await vite.listen();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ httpCredentials: { username: 'test', password }, baseURL: 'http://127.0.0.1:4178' });
const page = await context.newPage();
const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
let stopped = false;
const workerLoop = (async () => { while (!stopped) { if (!await worker.runOne() && !await analysis.runOne()) await new Promise(r => setTimeout(r, 25)); } })();
const checks: string[] = [];
try {
  assert.equal((await fetch(backendUrl + '/api/v1/sources')).status, 401);
  assert.equal((await fetch('http://127.0.0.1:4178/api/v1/sources')).status, 401);
  const auth = { Authorization: 'Basic ' + Buffer.from('test:' + password).toString('base64') };
  assert.equal((await fetch('http://127.0.0.1:4178/api/v1/sources', { headers: { ...auth, Origin: 'http://untrusted.invalid' } })).status, 403);
  for (const path of ['/.env', '/.data/browser.sqlite', '/@fs' + root + '/ria.sqlite']) assert.ok((await fetch('http://127.0.0.1:4178' + path, { headers: auth })).status >= 400);
  checks.push('Direct API/proxy authentication, cross-origin rejection and private-file denial');
  await page.goto('/#sources');
  await expect(page.locator('#mode')).toHaveValue('live');
  await page.locator('[data-run]').click();
  await expect(page.locator('#jobs')).toContainText('Succeeded', { timeout: 30000 });
  await expect.poll(() => db.get<{ n: number }>("SELECT count(*) n FROM version_analysis WHERE state='succeeded'")!.n).toBe(1);
  const row = db.get<{ id: string; current_version_id: string }>('SELECT id,current_version_id FROM publications')!;
  await page.goto('/#publication/' + row.id);
  await expect(page.getByRole('heading', { name: /Structured obligations/ })).toBeVisible();
  await expect(page.locator('.obligation blockquote')).toContainText('SYNTHETIC TEST ONLY');
  checks.push('UI monitoring → persisted discovery/text extraction → structured obligations with citations');
  await page.getByRole('button', { name: 'Run comparison', exact: true }).click();
  await expect(page.locator('#comparison')).toContainText('Blocked', { timeout: 30000 });
  await page.getByRole('button', { name: 'Upload missing predecessor' }).click();
  await page.locator('[name=file]').setInputFiles({ name: 'synthetic-predecessor.txt', mimeType: 'text/plain', buffer: Buffer.from(previous) });
  await page.locator('[name=title]').fill('SYNTHETIC stored predecessor');
  await page.locator('[name=sourceId]').selectOption(source.id);
  await page.locator('[name=referenceNumber]').fill('E2E/2020/1');
  await page.getByRole('button', { name: 'Upload & process' }).click();
  await expect(page.locator('#comparison')).toContainText(/Deadline changed/i, { timeout: 30000 });
  await expect(page.locator('.clause-grid')).toContainText('2026-12-31');
  await expect(page.locator('.clause-grid')).toContainText('2027-03-31');
  assert.ok(await page.locator('.clause-grid mark').count());
  await page.locator('#review-form [name=state]').selectOption('approved');
  await page.locator('#review-form [name=note]').fill('SYNTHETIC browser review; not regulatory evidence.');
  await page.getByRole('button', { name: 'Save review' }).click();
  await expect(page.locator('.state-strip')).toContainText('Approved');
  await page.reload(); await expect(page.locator('.state-strip')).toContainText('Approved');
  assert.equal(repository.detail(row.id).review.reviewedBy, reviewer);
  checks.push('UI missing predecessor → upload/link → cited comparison/highlights → review save/reload persistence');
  await page.goto('/#repository');
  await page.locator('[name=q]').fill('no such publication');
  await page.locator('#filters').evaluate((form: HTMLFormElement) => form.requestSubmit());
  await expect(page.locator('#content')).toContainText('No publications');
  await page.locator('[name=q]').fill(''); await page.locator('[name=changeClass]').selectOption('deadlineChanged');
  await page.locator('#filters').evaluate((form: HTMLFormElement) => form.requestSubmit());
  await expect(page.locator('#content')).toContainText('SYNTHETIC browser amendment');
  checks.push('UI search empty state and persisted change-class filter');
  await page.goto('/#sources');
  await page.locator('[name=monitoringIntervalMinutes]').fill('60');
  await page.locator('[data-source]').evaluate((form: HTMLFormElement) => form.requestSubmit());
  await expect.poll(() => repository.sourceById(source.id).config.monitoringIntervalMinutes).toBe(60);
  const updated = repository.sourceById(source.id).config;
  db.run('UPDATE sources SET config_json=? WHERE id=?', JSON.stringify({ ...updated, nextMonitorAt: '2020-01-01T00:00:00.000Z' }), source.id);
  repository.scheduleDue();
  await expect.poll(() => db.get<{ n: number }>("SELECT count(*) n FROM jobs WHERE kind='monitor' AND state='succeeded'")!.n).toBe(2);
  assert.equal(db.get<{ n: number }>('SELECT count(*) n FROM publications')!.n, 2);
  checks.push('UI frequency update → due scheduler → duplicate-free rerun');
  await page.goto('/#publication/' + randomUUID());
  await expect(page.getByRole('heading', { name: 'Unable to load this view' })).toBeVisible();
  await expect(page.locator('#notice')).toContainText('notFound');
  checks.push('UI structured API error state');
  assert.deepEqual(errors, []);
  await page.goto('/#publication/' + row.id); await expect(page.locator('.state-strip')).toContainText('Approved');
  await page.screenshot({ path: resolve(root, 'comparison-review.png'), fullPage: true });
  await writeFile(resolve(root, 'report.json'), JSON.stringify({ result: 'passed', inputKind: 'clearly-labelled-synthetic', realBrowser: true, model: 'synthetic', checks, publicationId: row.id, completedAt: new Date().toISOString() }, null, 2));
  console.log(JSON.stringify({ result: 'passed', checks, artifacts: root }, null, 2));
} catch (error) {
  await page.screenshot({ path: resolve(root, 'failure.png'), fullPage: true });
  await writeFile(resolve(root, 'report.json'), JSON.stringify({ result: 'failed', checks, failure: error instanceof Error ? error.message : String(error) }, null, 2));
  throw error;
} finally {
  stopped = true; await workerLoop; await browser.close(); await vite.close(); await new Promise<void>(done => backend.close(() => done())); db.close();
}
